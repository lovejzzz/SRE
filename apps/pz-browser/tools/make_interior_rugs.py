"""Original woven rugs. Deterministic 2:1 pixel art; no source-game pixels."""
from pathlib import Path
import struct
import zlib
import json

root = Path(__file__).resolve().parents[1]
styles = [('linen', 'Linen area rug', 3, 2, (186, 173, 145)),
          ('moss', 'Moss border rug', 3, 2, (110, 119, 87)),
          ('runner', 'Oatmeal entry runner', 2, 1, (169, 155, 128))]
pixels = bytearray(64 * 28 * 32 * 4)
regions, properties = {}, {}
index = 0
orientations = [(style + suffix, label, w if facing == 'N' else d, d if facing == 'N' else w, color, facing)
                for style, label, w, d, color in styles for suffix, facing in [('', 'N'), ('_w', 'W')]]
for style, label, width, depth, color, facing in orientations:
    for dx in range(width):
        for dy in range(depth):
            name = f'tian_rug_{style}_{dx*depth+dy}'
            for px in range(64):
                for py in range(32):
                    u = (px + .5 - 32) / 64 + (py + .5) / 32
                    v = (py + .5) / 32 - (px + .5 - 32) / 64
                    if not (0 <= u < 1 and 0 <= v < 1):
                        continue
                    a, b = dx + u, dy + v
                    edge = min(a, b, width-a, depth-b)
                    if edge < .07:
                        continue
                    noise = ((int(a*100)*13 + int(b*100)*7) % 9)-4
                    weave = 4 if (int(a*54)+int(b*54)) % 2 else -3
                    border = -26 if .1 < edge < .16 else (9 if .19 < edge < .23 else 0)
                    rgb = tuple(max(0, min(255, c + noise + weave + border)) for c in color)
                    offset = (py * 64 * 28 + index * 64 + px) * 4
                    pixels[offset:offset+4] = bytes((*rgb, 255))
            regions[name] = dict(page='original-interiors.png', x=index*64, y=0, w=64, h=32, ox=0, oy=96, scale=1)
            properties[name] = dict(CustomName=label, GroupName='Tian', Facing=facing, SpriteGridPos=f'{dx},{dy}', MoveType='FloorRug', FloorOverlay='', IsMoveAble='')
            index += 1
def chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind+data))
width = 64*28
raw = b''.join(b'\0'+pixels[y*width*4:(y+1)*width*4] for y in range(32))
png = b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR', struct.pack('>IIBBBBB', width, 32, 8, 6, 0, 0, 0))+chunk(b'IDAT', zlib.compress(raw, 9))+chunk(b'IEND', b'')
(root / 'private-assets/original-interiors.png').write_bytes(png)
data = json.dumps(dict(regions=regions, properties=properties), separators=(',', ':'))
(root / 'src/original-assets.js').write_text("import {installStudioAssets} from './studio-assets.js';\nimport {installMasonryAssets} from './masonry-assets.js';\nimport {installArchitecturalAssets} from './architectural-assets.js';\nimport {installCafeAssets} from './cafe-assets.js';\nimport {installHouseDetails} from './house-detail-assets.js';\n// Original Tian House art; generated by tools/make_interior_rugs.py.\nconst assets = "+data+';\nexport function installOriginalAssets(properties, atlas) { installStudioAssets(properties,atlas); installMasonryAssets(properties,atlas); installArchitecturalAssets(properties,atlas); installHouseDetails(properties,atlas); installCafeAssets(properties,atlas); Object.assign(properties, assets.properties); Object.assign(atlas.regions, assets.regions); }\n')
